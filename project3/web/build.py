"""Build the browser edition: one offline HTML file with the JavaScript engine inside.

    py -3 web/build.py

Tables the engine needs (the JPEG edge-pixel basis) are written from the Python modules,
so both editions compute with the very same numbers.
"""

import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, ".."))

from blockrecover import jpeg  # noqa: E402

ORDER = ["base", "tables", "features", "pdfcrypt", "pdflex", "inflate", "binfmt", "jpeg", "pdf", "streams", "word",
         "jpegfile", "recover"]


def tables_js():
    import math
    edge = [[float(x) for x in row] for row in jpeg.EDGE]
    # c/512 * log2(c/512) for every count c of a byte value in a 512-byte block, exactly as
    # Python computes it (JavaScript's Math.log2 can differ in the last bit)
    plogp = [0.0] + [c / 512 * math.log2(c / 512) for c in range(1, 513)]
    return ("// Generated by web/build.py from the Python modules. Do not edit.\n"
            "\"use strict\";\nBR.tables = " + json.dumps({"EDGE": edge, "PLOGP512": plogp}, separators=(",", ":")) + ";\n")


def write_tables():
    with open(os.path.join(HERE, "src", "tables.js"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write(tables_js())


def engine_js():
    write_tables()
    parts = []
    for name in ORDER:
        with open(os.path.join(HERE, "src", name + ".js"), encoding="utf-8") as fh:
            parts.append(fh.read())
    return "\n".join(parts)


def js_string(text):
    # a JavaScript string literal that is also safe inside a <script> element
    return json.dumps(text).replace("</", "<\\/").replace("\u2028", "\\u2028").replace("\u2029", "\\u2029")


def build(out=None):
    from blockrecover import report
    from blockrecover.theme import THEME_CSS, THEME_JS
    with open(os.path.join(HERE, "app.html"), encoding="utf-8") as fh:
        page = fh.read()
    with open(os.path.join(HERE, "app.js"), encoding="utf-8") as fh:
        app = fh.read()
    tpl = report.TEMPLATE.replace("/*CSS*/", THEME_CSS + report.PAGE_CSS).replace("/*JS*/", THEME_JS)
    page = (page.replace("/*CSS*/", THEME_CSS).replace("/*JS*/", THEME_JS).replace("/*APP*/", app)
            .replace("/*ENGINE*/", js_string(engine_js())).replace("/*REPORT*/", js_string(tpl)))
    out = out or os.path.join(HERE, "..", "BlockRecovery.html")
    with open(out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(page)
    return out


if __name__ == "__main__":
    print("written:", build(sys.argv[1] if len(sys.argv) > 1 else None))
